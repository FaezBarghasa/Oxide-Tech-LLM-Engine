//! OKIR CUDA C++ / PTX Target Emitter.

use super::ir::{OkirFunction, OkirOpcode};
use std::fmt::Write;

#[must_use]
pub fn emit_cuda_kernel(func: &OkirFunction) -> String {
    let mut code = String::with_capacity(1024);
    code.push_str("// Auto-generated by Oxide Kernel IR (OKIR) - CUDA Target\n");
    code.push_str("#include <cuda_fp16.h>\n\n");
    let _ = writeln!(code, "__global__ void {}_cuda(", func.name);

    for (name, dt) in &func.input_buffers {
        let ty = match dt {
            super::ir::OkirDataType::F32 => "const float*",
            super::ir::OkirDataType::F16 => "const __half*",
            super::ir::OkirDataType::I8 => "const int8_t*",
            _ => "const void*",
        };
        let _ = writeln!(code, "    {ty} __restrict__ {name},");
    }
    for (i, (name, dt)) in func.output_buffers.iter().enumerate() {
        let ty = match dt {
            super::ir::OkirDataType::F32 => "float*",
            super::ir::OkirDataType::F16 => "__half*",
            _ => "void*",
        };
        let comma = if i + 1 == func.output_buffers.len() {
            ""
        } else {
            ","
        };
        let _ = writeln!(code, "    {ty} __restrict__ {name}{comma}");
    }
    code.push_str(") {\n");
    code.push_str("    int idx = blockIdx.x * blockDim.x + threadIdx.x;\n");

    for inst in &func.instructions {
        match inst.opcode {
            OkirOpcode::Silu => {
                let op0 = inst.operands[0];
                let _ = writeln!(
                    code,
                    "    float r{} = r{op0} / (1.0f + __expf(-r{op0}));",
                    inst.dest_reg
                );
            }
            OkirOpcode::Mul => {
                let _ = writeln!(
                    code,
                    "    float r{} = r{} * r{};",
                    inst.dest_reg, inst.operands[0], inst.operands[1]
                );
            }
            OkirOpcode::Add => {
                let _ = writeln!(
                    code,
                    "    float r{} = r{} + r{};",
                    inst.dest_reg, inst.operands[0], inst.operands[1]
                );
            }
            OkirOpcode::WarpReduceSum => {
                let r_dest = inst.dest_reg;
                let r_src = inst.operands[0];
                let _ = writeln!(code, "    float r{r_dest} = r{r_src};");
                code.push_str("    #pragma unroll\n");
                code.push_str("    for (int offset = 16; offset > 0; offset >>= 1) {\n");
                let _ = writeln!(
                    code,
                    "        r{r_dest} += __shfl_down_sync(0xFFFFFFFF, r{r_dest}, offset);"
                );
                code.push_str("    }\n");
            }
            _ => {}
        }
    }

    code.push_str("}\n");
    code
}
