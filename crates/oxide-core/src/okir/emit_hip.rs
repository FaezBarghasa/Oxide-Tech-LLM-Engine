//! OKIR AMD ROCm HIP Target Emitter (CDNA-64 / RDNA-32 Wavefront Aware).

use super::ir::{OkirFunction, OkirOpcode};
use std::fmt::Write;

#[must_use]
pub fn emit_hip_kernel(func: &OkirFunction, is_cdna: bool) -> String {
    let mut code = String::with_capacity(1024);
    let wave_size = if is_cdna { 64 } else { 32 };

    code.push_str("// Auto-generated by Oxide Kernel IR (OKIR) - ROCm HIP Target\n");
    code.push_str("#include <hip/hip_runtime.h>\n");
    code.push_str("#include <hip/hip_fp16.h>\n\n");
    let _ = writeln!(code, "#define OXIDE_WAVEFRONT_SIZE {wave_size}\n");
    let _ = writeln!(code, "__global__ void {}_hip(", func.name);

    for (name, dt) in &func.input_buffers {
        let ty = match dt {
            super::ir::OkirDataType::F32 => "const float*",
            super::ir::OkirDataType::F16 => "const __half*",
            _ => "const void*",
        };
        let _ = writeln!(code, "    {ty} __restrict__ {name},");
    }
    for (i, (name, dt)) in func.output_buffers.iter().enumerate() {
        let ty = match dt {
            super::ir::OkirDataType::F32 => "float*",
            super::ir::OkirDataType::F16 => "__half*",
            _ => "void*",
        };
        let comma = if i + 1 == func.output_buffers.len() {
            ""
        } else {
            ","
        };
        let _ = writeln!(code, "    {ty} __restrict__ {name}{comma}");
    }
    code.push_str(") {\n");
    code.push_str("    int idx = hipBlockIdx_x * hipBlockDim_x + hipThreadIdx_x;\n");

    for inst in &func.instructions {
        match inst.opcode {
            OkirOpcode::Silu => {
                let op0 = inst.operands[0];
                let _ = writeln!(
                    code,
                    "    float r{} = r{op0} / (1.0f + __expf(-r{op0}));",
                    inst.dest_reg
                );
            }
            OkirOpcode::Mul => {
                let _ = writeln!(
                    code,
                    "    float r{} = r{} * r{};",
                    inst.dest_reg, inst.operands[0], inst.operands[1]
                );
            }
            OkirOpcode::Add => {
                let _ = writeln!(
                    code,
                    "    float r{} = r{} + r{};",
                    inst.dest_reg, inst.operands[0], inst.operands[1]
                );
            }
            OkirOpcode::WarpReduceSum => {
                let r_dest = inst.dest_reg;
                let r_src = inst.operands[0];
                let _ = writeln!(code, "    float r{r_dest} = r{r_src};");
                code.push_str("    #pragma unroll\n");
                code.push_str(
                    "    for (int offset = OXIDE_WAVEFRONT_SIZE / 2; offset > 0; offset >>= 1) {\n",
                );
                let _ = writeln!(
                    code,
                    "        r{r_dest} += __shfl_down(r{r_dest}, offset, OXIDE_WAVEFRONT_SIZE);"
                );
                code.push_str("    }\n");
            }
            _ => {}
        }
    }

    code.push_str("}\n");
    code
}
