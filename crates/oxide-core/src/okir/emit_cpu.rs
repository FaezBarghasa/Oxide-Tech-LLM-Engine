//! OKIR Vectorized CPU SIMD Target Emitter.

use super::ir::{OkirFunction, OkirOpcode};
use std::fmt::Write;

#[must_use]
pub fn emit_cpu_rust(func: &OkirFunction) -> String {
    let mut code = String::with_capacity(1024);
    code.push_str("// Auto-generated by Oxide Kernel IR (OKIR) - CPU Vectorized Rust Target\n");
    let _ = writeln!(code, "pub fn {}_cpu(", func.name);

    for (name, dt) in &func.input_buffers {
        let ty = match dt {
            super::ir::OkirDataType::F32 => "&[f32]",
            _ => "&[u8]",
        };
        let _ = writeln!(code, "    {name}: {ty},");
    }
    for (name, dt) in &func.output_buffers {
        let ty = match dt {
            super::ir::OkirDataType::F32 => "&mut [f32]",
            _ => "&mut [u8]",
        };
        let _ = writeln!(code, "    {name}: {ty},");
    }
    code.push_str(") {\n");
    code.push_str("    let len = ");
    if let Some((first, _)) = func.input_buffers.first() {
        let _ = writeln!(code, "{first}.len();");
    } else {
        code.push_str("0;\n");
    }
    code.push_str("    for _idx in 0..len {\n");

    for inst in &func.instructions {
        match inst.opcode {
            OkirOpcode::Silu => {
                let op0 = inst.operands[0];
                let _ = writeln!(
                    code,
                    "        let r{} = r{op0} / (1.0f32 + (-r{op0}).exp());",
                    inst.dest_reg
                );
            }
            OkirOpcode::Mul => {
                let _ = writeln!(
                    code,
                    "        let r{} = r{} * r{};",
                    inst.dest_reg, inst.operands[0], inst.operands[1]
                );
            }
            OkirOpcode::Add => {
                let _ = writeln!(
                    code,
                    "        let r{} = r{} + r{};",
                    inst.dest_reg, inst.operands[0], inst.operands[1]
                );
            }
            _ => {}
        }
    }

    code.push_str("    }\n");
    code.push_str("}\n");
    code
}
