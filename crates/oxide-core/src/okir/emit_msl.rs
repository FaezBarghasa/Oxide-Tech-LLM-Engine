//! OKIR Apple Metal Shading Language (MSL) Target Emitter.

use super::ir::{OkirFunction, OkirOpcode};
use std::fmt::Write;

#[must_use]
pub fn emit_msl_kernel(func: &OkirFunction) -> String {
    let mut code = String::with_capacity(1024);
    code.push_str("// Auto-generated by Oxide Kernel IR (OKIR) - Metal Shading Language\n");
    code.push_str("#include <metal_stdlib>\nusing namespace metal;\n\n");
    let _ = writeln!(code, "kernel void {}_msl(", func.name);

    let mut buf_idx = 0;
    for (name, dt) in &func.input_buffers {
        let ty = match dt {
            super::ir::OkirDataType::F32 => "device const float*",
            super::ir::OkirDataType::F16 => "device const half*",
            _ => "device const void*",
        };
        let _ = writeln!(code, "    {ty} {name} [[buffer({buf_idx})]],");
        buf_idx += 1;
    }
    for (name, dt) in &func.output_buffers {
        let ty = match dt {
            super::ir::OkirDataType::F32 => "device float*",
            super::ir::OkirDataType::F16 => "device half*",
            _ => "device void*",
        };
        let _ = writeln!(code, "    {ty} {name} [[buffer({buf_idx})]],");
        buf_idx += 1;
    }
    code.push_str("    uint gid [[thread_position_in_grid]],\n");
    code.push_str("    uint simd_lane [[thread_index_in_simdgroup]]\n");
    code.push_str(") {\n");

    for inst in &func.instructions {
        match inst.opcode {
            OkirOpcode::Silu => {
                let op0 = inst.operands[0];
                let _ = writeln!(
                    code,
                    "    float r{} = r{op0} / (1.0f + metal::exp(-r{op0}));",
                    inst.dest_reg
                );
            }
            OkirOpcode::Mul => {
                let _ = writeln!(
                    code,
                    "    float r{} = r{} * r{};",
                    inst.dest_reg, inst.operands[0], inst.operands[1]
                );
            }
            OkirOpcode::Add => {
                let _ = writeln!(
                    code,
                    "    float r{} = r{} + r{};",
                    inst.dest_reg, inst.operands[0], inst.operands[1]
                );
            }
            OkirOpcode::WarpReduceSum => {
                let _ = writeln!(
                    code,
                    "    float r{} = simd_sum(r{});",
                    inst.dest_reg, inst.operands[0]
                );
            }
            _ => {}
        }
    }

    code.push_str("}\n");
    code
}
